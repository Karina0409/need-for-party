"""
Маппинг ролей для исправления опечаток в БД
"""

ROLE_MAPPINGS = {
    # Правильное название: Название в БД
    'Ас танцпола': 'Ас танспола',  # Исправляем опечатку
    'Ас тусовок': 'Ас тусовок',
    'Весельчак': 'Весельчак',
    'Ведущий': 'Ведущий',
    'Глава бара': 'Глава бара',
    'Диджей': 'Диджей',
    'Душа компании': 'Душа компании',
    'Легенда': 'Легенда',
    'Любитель выпить': 'Любитель выпить',
    'Организатор': 'Организатор',
    'Охрана': 'Охрана',
    'Рисковый': 'Рисковый',
    'Танцор': 'Танцор',
    'Тусовщик': 'Тусовщик',
    'Участник': 'Участник',
    'Админ': 'Админ',
    'Бармен': 'Бармен'
}

def get_db_role_name(display_name):
    """Получить название роли как оно хранится в БД"""
    return ROLE_MAPPINGS.get(display_name, display_name)

def get_display_role_name(db_name):
    """Получить красивое название роли для отображения"""
    reverse_mapping = {v: k for k, v in ROLE_MAPPINGS.items()}
    return reverse_mapping.get(db_name, db_name)